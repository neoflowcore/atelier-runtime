import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const lockPath = resolve(root, "integrations/gpt-bridge/upstream.lock.json");
const lock = JSON.parse(readFileSync(lockPath, "utf8"));

const work = resolve(root, ".tmp/gpt-bridge-import");
const checkout = resolve(work, "repo");
const destination = resolve(root, lock.destination);

function run(args, cwd = root) {
  return execFileSync("git", args, {
    cwd,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  }).trim();
}

rmSync(work, { recursive: true, force: true });
mkdirSync(work, { recursive: true });

run(["clone", "--no-tags", "--filter=blob:none", lock.upstream, checkout]);
run(["fetch", "--depth=1", "origin", lock.commit], checkout);
run(["checkout", "--detach", lock.commit], checkout);

const actual = run(["rev-parse", "HEAD"], checkout);
if (actual !== lock.commit) {
  throw new Error(`GPT-Bridge import identity mismatch: expected ${lock.commit}, got ${actual}`);
}

const status = run(["status", "--porcelain"], checkout);
if (status !== "") {
  throw new Error("GPT-Bridge upstream checkout is unexpectedly dirty");
}

const pkg = JSON.parse(readFileSync(resolve(checkout, "package.json"), "utf8"));
if (pkg.license !== lock.license) {
  throw new Error(`GPT-Bridge license mismatch: expected ${lock.license}, got ${pkg.license}`);
}

rmSync(destination, { recursive: true, force: true });
mkdirSync(destination, { recursive: true });

for (const rel of lock.include) {
  const src = resolve(checkout, rel);
  if (!existsSync(src)) {
    throw new Error(`GPT-Bridge import path missing: ${rel}`);
  }
  cpSync(src, resolve(destination, rel), {
    recursive: true,
    force: true,
    dereference: false,
  });
}

const provenance = [
  "# GPT-Bridge imported snapshot",
  "",
  `- upstream: ${lock.upstream}`,
  `- commit: \`${lock.commit}\``,
  `- package version: \`${pkg.version}\``,
  `- license declaration: \`${pkg.license}\``,
  "",
  "This directory is generated by scripts/sync-gpt-bridge-upstream.mjs.",
  "Do not hand-edit generated upstream files without recording an explicit Atelier patch/delta.",
  "",
].join("\n");

await import("node:fs").then(({ writeFileSync }) => {
  writeFileSync(resolve(destination, "ATELIER_UPSTREAM_PROVENANCE.md"), provenance, "utf8");
});

rmSync(work, { recursive: true, force: true });

console.log(JSON.stringify({
  imported: true,
  upstream: lock.upstream,
  commit: lock.commit,
  destination: lock.destination,
  paths: lock.include,
}, null, 2));
